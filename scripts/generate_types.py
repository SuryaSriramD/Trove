"""Generate transport types from normative JSON Schema. Do not hand-edit output."""
import argparse, json, os, re, subprocess
from codegen_output import publish
from devtools import cache_dir, go_binary
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Report drift without changing generated files')
parser.add_argument('--cache', type=Path, default=cache_dir())
args = parser.parse_args()
# Resolve the pinned formatter before preparing any consumer output.
go = go_binary(args.cache)
goroot = Path(subprocess.check_output([go, 'env', 'GOROOT'], text=True, env=dict(os.environ, GOTOOLCHAIN='local')).strip())
gofmt = goroot / 'bin' / ('gofmt.exe' if os.name == 'nt' else 'gofmt')
if not gofmt.is_file(): raise SystemExit('Pinned Go installation is missing gofmt')
outputs = {}
SCHEMAS={k:json.loads((ROOT/'contracts'/f'{k}.schema.json').read_text()) for k in ('domain','service','jobs')}
OUT=ROOT/'contracts'/'generated'
def ident(s): return ''.join(x[:1].upper()+x[1:] for x in re.split('[^a-zA-Z0-9]',s))
def ref(s,mod):
    path,name=s.split('#/$defs/')
    return (path.split('.')[0] if path else mod),name
def ts(s,mod):
    if '$ref' in s:
        m,n=ref(s['$ref'],mod); return (m+'.' if m!=mod else '')+n
    if 'const' in s: return json.dumps(s['const'])
    if 'enum' in s: return ' | '.join(json.dumps(x) for x in s['enum'])
    if ('oneOf' in s or 'anyOf' in s) and not s.get('properties'): return '('+' | '.join(ts(x,mod) for x in s.get('oneOf',s.get('anyOf')))+')'
    t=s.get('type')
    if isinstance(t,list): return 'unknown'
    if t=='object':
        if not s.get('properties'): return '{ [key: string]: unknown }'
        return '{ '+ ' '.join(f'{json.dumps(k)}'+('' if k in s.get('required',[]) else '?')+': '+ts(v,mod)+';' for k,v in s['properties'].items())+' }'
    if t=='array': return 'Array<'+ts(s.get('items',{}),mod)+'>'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(t,'unknown')
for mod,sc in SCHEMAS.items():
    lines=['// Generated by scripts/generate_types.py. Validate untrusted JSON against the source schemas.']
    lines += [f'import type * as {m} from "./{m}";' for m in SCHEMAS if m!=mod]
    lines += [f'export type {n} = {ts(s,mod)};' for n,s in sc['$defs'].items()]
    outputs[OUT/f'{mod}.ts'] = ('\n'.join(lines)+'\n').encode()
# Go structs and closed tagged unions retain the same JSON shape as TypeScript.
# Struct decode is followed by Validate; static types intentionally do not replace schema checks.
GO=[]; extras={}; done=set()
def name(mod,n): return ident(mod)+ident(n)
def deref(s,mod):
    if '$ref' not in s:return s,mod
    m,n=ref(s['$ref'],mod);return deref(SCHEMAS[m]['$defs'][n],m)
def optional_nullable(s):
    return [k for k,v in s.get('properties',{}).items()
            if k not in s.get('required',[]) and
            any(x.get('type')=='null' for x in v.get('oneOf',v.get('anyOf',[])))]
def gotype(s,mod,hint):
    if '$ref' in s:
        m,n=ref(s['$ref'],mod);return name(m,n)
    union=None if s.get('properties') else s.get('oneOf',s.get('anyOf'))
    if union:
        nonnull=[x for x in union if x.get('type')!='null']
        if len(nonnull)==1 and len(union)==2:return '*'+gotype(nonnull[0],mod,hint)
        types={deref(x,mod)[0].get('type','string' if 'const' in x and isinstance(x['const'],str) else None) for x in union}
        if types=={'string'}:return 'string'
        extras[hint]=(s,mod);return hint
    if 'const' in s:
        v=s['const'];return 'bool' if isinstance(v,bool) else 'int64' if isinstance(v,int) else 'string'
    t=s.get('type')
    if isinstance(t,list) or not t:return 'json.RawMessage'
    if t=='object':
        if not s.get('properties'):return 'map[string]json.RawMessage'
        fields=[]
        for k,v in s['properties'].items():
            typ=gotype(v,mod,hint+ident(k));optional=k not in s.get('required',[])
            if optional and not typ.startswith(('*','[]','map[')) and typ!='json.RawMessage':typ='*'+typ
            fields.append(f'{ident(k)} {typ} `json:"{k}'+(',omitempty' if optional else '')+'"`')
        for k in optional_nullable(s):
            fields.append(f'{ident(k)}Present bool `json:"-"` // Set true to encode an explicit null when the value is nil.')
        return 'struct {\n'+'\n'.join(fields)+'\n}'
    if t=='array':return '[]'+gotype(s.get('items',{}),mod,hint+'Item')
    return {'string':'string','integer':'int64','number':'float64','boolean':'bool','null':'json.RawMessage'}.get(t,'json.RawMessage')
def emit(n,s,mod):
    if n in done:return
    done.add(n)
    union=None if s.get('properties') else s.get('oneOf',s.get('anyOf'))
    if union and all(deref(x,mod)[0].get('type')=='object' for x in union):
        variants=[]
        for i,x in enumerate(union):
            raw,m=deref(x,mod)
            if '$ref' in x:
                rm,rn=ref(x['$ref'],mod);vn=name(rm,rn)
            else:
                vn=n+'Variant'+str(i+1);extras[vn]=(x,mod)
            variants.append((vn,raw))
        GO.append(f'type {n}Value interface {{ is{n}() }}\ntype {n} struct {{ Value {n}Value }}')
        for vn,_ in variants:GO.append(f'func ({vn}) is{n}() {{}}')
        GO.append(f'func (v {n}) MarshalJSON() ([]byte,error) {{ return json.Marshal(v.Value) }}')
        code=[f'func (v *{n}) UnmarshalJSON(data []byte) error {{','var fields map[string]json.RawMessage','if err := json.Unmarshal(data, &fields); err != nil {return err}']
        for vn,raw in variants:
            required=raw.get('required',[]);consts={k:p['const'] for k,p in raw.get('properties',{}).items() if 'const' in p}
            r='[]string{'+','.join(json.dumps(k) for k in required)+'}'
            c='map[string]string{'+','.join(json.dumps(k)+':'+json.dumps(json.dumps(x,separators=(',',':'))) for k,x in consts.items())+'}'
            enums={k:p['enum'] for k,p in raw.get('properties',{}).items() if 'enum' in p}
            e='map[string][]string{'+','.join(json.dumps(k)+':{'+','.join(json.dumps(json.dumps(x,separators=(',',':'))) for x in values)+'}' for k,values in enums.items())+'}'
            a='[]string{'+','.join(json.dumps(k) for k in raw.get('properties',{}))+'}'
            code.append(f'if matchesVariant(fields,{r},{c},{e},{a}) {{ var result {vn}; if err := json.Unmarshal(data,&result); err != nil {{return err}}; v.Value=result; return nil }}')
        code+=['return fmt.Errorf("unknown or incomplete '+n+' variant")','}'];GO.append('\n'.join(code))
    else:
        typ=gotype(s,mod,n)
        GO.append(f'type {n} '+('= ' if typ=='json.RawMessage' else '')+typ)
        nullable=optional_nullable(s)
        if nullable:
            code=[f'func (v *{n}) UnmarshalJSON(data []byte) error {{',f'type plain {n}',
                  'var decoded plain; if err := json.Unmarshal(data,&decoded); err != nil {return err}',
                  'var fields map[string]json.RawMessage; if err := json.Unmarshal(data,&fields); err != nil {return err}']
            for k in nullable: code.append(f'_, decoded.{ident(k)}Present = fields[{json.dumps(k)}]')
            code += [f'*v = {n}(decoded); return nil','}']
            GO.append('\n'.join(code))
            code=[f'func (v {n}) MarshalJSON() ([]byte,error) {{',f'type plain {n}',
                  'raw,err := json.Marshal(plain(v)); if err != nil {return nil,err}',
                  'var fields map[string]json.RawMessage; if err = json.Unmarshal(raw,&fields); err != nil {return nil,err}']
            for k in nullable: code.append(f'if v.{ident(k)}Present && v.{ident(k)} == nil {{fields[{json.dumps(k)}] = json.RawMessage("null")}}')
            code += ['return json.Marshal(fields)','}']
            GO.append('\n'.join(code))
for mod,sc in SCHEMAS.items():
    for n,s in sc['$defs'].items():emit(name(mod,n),s,mod)
while any(n not in done for n in extras):
    for n,(s,m) in list(extras.items()):emit(n,s,m)
preamble='''// Code generated by scripts/generate_types.py; DO NOT EDIT.
package contracts
import ("encoding/json"; "fmt")
func matchesVariant(fields map[string]json.RawMessage, required []string, constants map[string]string, enums map[string][]string, allowed []string) bool {
 for _, k := range required { if _, ok := fields[k]; !ok { return false } }
 for k := range fields { found:=false; for _,a := range allowed {if k==a {found=true}}; if !found{return false} }
 for k,values := range enums {if raw,ok:=fields[k];ok {found:=false;for _,v:=range values {if string(raw)==v {found=true}};if !found{return false}}}
 for k,v := range constants { if string(fields[k]) != v { return false } }
 return true
}
'''
# Written in contracts so embed patterns can include canonical source schemas.
outputs[ROOT/'contracts'/'types_generated.go'] = subprocess.run([str(gofmt)], input=(preamble+'\n'.join(GO)+'\n').encode(), stdout=subprocess.PIPE, check=True).stdout
publish(outputs, check=args.check)
