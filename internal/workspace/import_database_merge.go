type ImportEntityIdentity struct {
	Kind     string `json:"kind"`
	SourceID string `json:"sourceId"`
	ID       string `json:"id"`
}

func trackImportIdentity(p *ImportPlan, kind, source, id string) {
	p.EntityIdentities = append(p.EntityIdentities, ImportEntityIdentity{kind, source, id})
}

func reuseImportDatabaseIdentities(ctx context.Context, q querier, p *ImportPlan) error {
	if len(p.PortableCollections) == 0 {
		return nil
	}
	for _, identity := range p.NotionIdentities {
		trackImportIdentity(p, identity.Kind, identity.SourceID, identity.ID)
	}
	remap := map[string]string{}
	for i := range p.EntityIdentities {
		identity := &p.EntityIdentities[i]
		var local string
		err := q.QueryRowContext(ctx, "SELECT local_id FROM import_entity_ids WHERE source_system=? AND source_namespace=? AND entity_kind=? AND source_identity=?", p.SourceSystem, p.Namespace, identity.Kind, identity.SourceID).Scan(&local)
		if errors.Is(err, sql.ErrNoRows) && p.SourceSystem == "notion_api" && identity.Kind != "option" {
			err = q.QueryRowContext(ctx, "SELECT local_id FROM import_mappings WHERE source_system=? AND source_namespace=? AND external_kind=? AND identity_kind='external_id' AND identity_value=?", p.SourceSystem, p.Namespace, identity.Kind, identity.SourceID).Scan(&local)
		}
		if err == nil {
			remap[identity.ID] = local
			identity.ID = local
		} else if !errors.Is(err, sql.ErrNoRows) {
			return err
		}
	}
	remapImportDatabaseEntities(p, remap)
	p.TypedDatabaseMerge = true
	return nil
}
func remapImportDatabaseEntities(p *ImportPlan, ids map[string]string) {
	ref := func(id string) string {
		if value := ids[id]; value != "" {
			return value
		}
		return id
	}
	for i := range p.NotionIdentities {
		p.NotionIdentities[i].ID = ref(p.NotionIdentities[i].ID)
	}
	for i := range p.NotionContainers {
		c := &p.NotionContainers[i]
		c.ID = ref(c.ID)
		for j := range c.Collections {
			c.Collections[j] = ref(c.Collections[j])
		}
	}
	for i := range p.Items {
		p.Items[i].CollectionID = ref(p.Items[i].CollectionID)
		p.Items[i].RecordID = ref(p.Items[i].RecordID)
		for j := range p.Items[i].Columns {
			p.Items[i].Columns[j].PropertyID = ref(p.Items[i].Columns[j].PropertyID)
		}
	}
	for i := range p.PortableCollections {
		c := &p.PortableCollections[i]
		c.CollectionID = ref(c.CollectionID)
		for j := range c.Properties {
			prop := &c.Properties[j]
			prop.Id = contracts.DomainId(ref(string(prop.Id)))
			prop.CollectionId = contracts.DomainId(c.CollectionID)
			var cfg any
			_ = json.Unmarshal(prop.Config, &cfg)
			prop.Config = marshal(rewritePortableDatabaseValue(cfg, ids, ""))
		}
		for j := range c.Records {
			r := &c.Records[j]
			r.ID = ref(r.ID)
			for k := range r.KnownProperties {
				r.KnownProperties[k] = ref(r.KnownProperties[k])
			}
			values := map[string]any{}
			for id, value := range r.Values {
				mapped := ref(id)
				kind := ""
				for _, prop := range c.Properties {
					if string(prop.Id) == mapped {
						kind = prop.Type
					}
				}
				values[mapped] = rewritePortablePropertyValue(value, kind, ids)
			}
			r.Values = values
		}
		for j := range c.Views {
			v := &c.Views[j]
			v.ID = ref(v.ID)
			v.ContainerID = ref(v.ContainerID)
			v.Config = rewritePortableDatabaseValue(v.Config, ids, "").(map[string]any)
			v.Query = rewritePortableDatabaseValue(v.Query, ids, "").(map[string]any)
		}
	}
	// This inert template payload is generated by our Notion normalizer. Rewrite
	// its typed reference slots, never arbitrary UUID-looking user prose.
	for i := range p.Items {
		item := &p.Items[i]
		if item.Kind != "notion_template" {
			continue
		}
		for j := range item.Blocks {
			block := &item.Blocks[j]
			const prefix = "Inactive imported template defaults:\n"
			text := str(block.Data["readableText"])
			if block.Type != "unsupported_external" || !strings.HasPrefix(text, prefix) {
				continue
			}
			var supplied map[string]any
			if json.Unmarshal([]byte(strings.TrimPrefix(text, prefix)), &supplied) != nil {
				continue
			}
			values := map[string]any{}
			for _, raw := range asList(supplied["propertyDefinitions"]) {
				prop := asObject(raw)
				id := str(prop["id"])
				if value, exists := asObject(supplied["propertyValues"])[id]; exists {
					values[ref(id)] = rewritePortablePropertyValue(value, str(prop["type"]), ids)
				}
			}
			supplied = rewritePortableDatabaseValue(supplied, ids, "").(map[string]any)
			supplied["propertyValues"] = values
			block.Data["readableText"] = prefix + string(marshal(supplied))
		}
	}
}
func copyImportDatabaseIdentities(p *ImportPlan) {
	ids := map[string]string{}
	for _, identity := range p.EntityIdentities {
		ids[identity.ID] = NewID()
	}
	remapImportDatabaseEntities(p, ids)
}
func persistImportDatabaseIdentities(m *Mutation, p *ImportPlan) error {
	if p.NotionCopyGraph {
		return nil
	}
	for _, identity := range p.EntityIdentities {
		table := entityTables[identity.Kind]
		if identity.Kind == "option" {
			table = "property_options"
		}
		if table == "" {
			return Fail("INTEGRITY_ERROR", "Unknown retained source identity kind")
		}
		var exists int
		if err := m.Tx.QueryRowContext(m.Context, "SELECT count(*) FROM "+table+" WHERE id=?", identity.ID).Scan(&exists); err != nil {
			return err
		}
		// Keeping the local schema does not create the incoming property or
		// option. Its pending evidence must not claim a canonical mapping.
		if exists == 0 {
			continue
		}
		var old string
		err := m.Tx.QueryRowContext(m.Context, "SELECT local_id FROM import_entity_ids WHERE source_system=? AND source_namespace=? AND entity_kind=? AND source_identity=?", p.SourceSystem, p.Namespace, identity.Kind, identity.SourceID).Scan(&old)
		if err == nil {
			if old != identity.ID {
				return Fail("CONFLICT", "A source identity was imported after this preview")
			}
			continue
		}
		if !errors.Is(err, sql.ErrNoRows) {
			return err
		}
		if _, err = m.Exec("INSERT INTO import_entity_ids VALUES(?,?,?,?,?)", p.SourceSystem, p.Namespace, identity.Kind, identity.SourceID, identity.ID); err != nil {
			return err
		}
	}
	return nil
}
func importCollectionFor(p *ImportPlan, item *ImportItem) *PortableCollectionImport {
	if item.Kind != "portable_collection" {
		return nil
	}
	for i := range p.PortableCollections {
		if p.PortableCollections[i].CollectionID == item.CollectionID {
			return &p.PortableCollections[i]
		}
	}
	return nil
}
func importPropertyField(prop contracts.DomainPropertyDefinition) json.RawMessage {
	return marshal(map[string]any{"name": prop.Name, "type": prop.Type, "schemaVersion": prop.SchemaVersion, "config": json.RawMessage(prop.Config)})
}
func addIncomingDatabaseFields(snapshot *ImportSnapshot, c *PortableCollectionImport) {
	snapshot.SourceScope = c.SourceScope
	snapshot.Fields["/collectionTitle"] = marshal(c.Title)
	for _, prop := range c.Properties {
		snapshot.Fields["/schema/"+string(prop.Id)] = importPropertyField(prop)
	}
	for _, record := range c.Records {
		snapshot.Fields["/records/"+record.ID] = marshal(record.PageID)
		for property, value := range record.Values {
			snapshot.Fields["/values/"+record.ID+"/"+property] = marshal(value)
		}
	}
}
func addLocalDatabaseFields(ctx context.Context, q querier, snapshot *ImportSnapshot, item *ImportItem, c *PortableCollectionImport) error {
	item.MergeGuards = map[string]string{}
	guard := func(kind, id, revision string) { item.MergeGuards[guardKey(kind, id)] = revision }
	var title, revision string
	if err := q.QueryRowContext(ctx, "SELECT title,revision FROM collections WHERE id=?", c.CollectionID).Scan(&title, &revision); err != nil {
		return err
	}
	guard("collection", c.CollectionID, revision)
	snapshot.Fields["/collectionTitle"] = marshal(title)
	rows, err := q.QueryContext(ctx, "SELECT id FROM properties WHERE collection_id=? ORDER BY id", c.CollectionID)
	if err != nil {
		return err
	}
	ids := []string{}
	for rows.Next() {
		var id string
		if err = rows.Scan(&id); err != nil {
			rows.Close()
			return err
		}
		ids = append(ids, id)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	for _, id := range ids {
		prop, err := propertyDefinition(ctx, q, id)
		if err != nil {
			return err
		}
		guard("property", id, string(prop.Revision))
		snapshot.Fields["/schema/"+id] = importPropertyField(prop)
	}
	records, err := readRecords(ctx, q, c.CollectionID)
	if err != nil {
		return err
	}
	for _, r := range records {
		guard("record", string(r.Id), string(r.Revision))
		var pageRevision string
		if err := q.QueryRowContext(ctx, "SELECT revision FROM pages WHERE id=?", r.PageId).Scan(&pageRevision); err != nil {
			return err
		}
		guard("page", string(r.PageId), pageRevision)
		var deleted sql.NullString
		if err := q.QueryRowContext(ctx, "SELECT deleted_at FROM pages WHERE id=?", r.PageId).Scan(&deleted); err != nil {
			return err
		}
		if deleted.Valid {
			continue
		}
		snapshot.Fields["/records/"+string(r.Id)] = marshal(r.PageId)
		for _, value := range r.Values {
			var titleValue map[string]any
			if json.Unmarshal(value.Value, &titleValue) == nil && titleValue["pageId"] != nil {
				continue
			}
			snapshot.Fields["/values/"+string(r.Id)+"/"+string(value.PropertyId)] = value.Value
		}
	}
	return nil
}

func checkImportMergeGuards(m *Mutation, item *ImportItem) error {
	for key, want := range item.MergeGuards {
		parts := strings.SplitN(key, ":", 2)
		if len(parts) != 2 {
			return Fail("INTEGRITY_ERROR", "Invalid retained import guard")
		}
		if err := guardImport(m, parts[0], parts[1]); err != nil {
			return err
		}
		if m.GuardRevision(parts[0], parts[1]) != want {
			return Fail("CONFLICT", "Database changed after import review; create a new preview")
		}
		if err := m.Kernel.authorizeEntity(m.Context, m.Tx, m.Execution, parts[0], parts[1]); err != nil {
			return err
		}
	}
	return nil
}

func selectedImportDatabaseFields(item *ImportItem) map[string]json.RawMessage {
	if item.ResolvedFields != nil {
		return item.ResolvedFields
	}
	if item.Choice == "keep_local" && item.Merge != nil {
		out := map[string]json.RawMessage{}
		for _, field := range item.Merge.Fields {
			if field.Local.Present {
				out[field.Path] = field.Local.Value
			}
		}
		return out
	}
	if item.Incoming != nil {
		return item.Incoming.Fields
	}
	return nil
}

// Reject unsupported schema migrations before any resumable page unit writes.
func validateReviewedImportDatabase(ctx context.Context, q querier, p *ImportPlan) error {
	if _, err := hiddenImportCollections(ctx, q, p); err != nil {
		return err
	}
	journalChanges := 0
	for i := range p.Items {
		item := &p.Items[i]
		if item.Kind != "portable_collection" || item.Choice == "duplicate" || p.NotionCopyGraph {
			continue
		}
		fields := selectedImportDatabaseFields(item)
		deletions, err := importRecordDeletions(ctx, q, p, item)
		if err != nil {
			return err
		}
		journalChanges += len(deletions)
		for _, path := range sortedImportPaths(fields, "/schema/") {
			var incoming struct {
				Name          string          `json:"name"`
				Type          string          `json:"type"`
				SchemaVersion int64           `json:"schemaVersion"`
				Config        json.RawMessage `json:"config"`
			}
			if err := json.Unmarshal(fields[path], &incoming); err != nil || incoming.SchemaVersion != 1 || contracts.Validate("domain", "property_"+incoming.Type+"_config_v1", incoming.Config) != nil {
				return Fail("INVALID_REQUEST", "Invalid reviewed property definition")
			}
			current, err := propertyDefinition(ctx, q, strings.TrimPrefix(path, "/schema/"))
			if errors.Is(err, sql.ErrNoRows) {
				continue
			}
			if err != nil {
				return err
			}
			if string(current.CollectionId) != item.CollectionID {
				return Fail("CONFLICT", "A property cannot move to another collection during import")
			}
			if current.Type != incoming.Type {
				journalChanges++
				if err := validateImportSchemaChange(ctx, q, item, strings.TrimPrefix(path, "/schema/"), fields[path], fields); err != nil {
					return err
				}
			}
			if current.Type == "relation" && !equalImportPresence(ImportPresence{true, current.Config}, ImportPresence{true, incoming.Config}) {
				return Fail("CONFLICT", "Changing relation configuration requires a separate migration; keep local schema or import a copy")
			}
		}
		if item.Merge != nil {
			for _, field := range item.Merge.Fields {
				if strings.HasPrefix(field.Path, "/schema/") && field.Local.Present && fields[field.Path] == nil {
					journalChanges++
					if c := importCollectionFor(p, item); c == nil || !c.SchemaComplete {
						return Fail("CONFLICT", "Incomplete schema enumeration cannot establish a source property deletion")
					}
					if err := validateImportSchemaChange(ctx, q, item, strings.TrimPrefix(field.Path, "/schema/"), nil, fields); err != nil {
						return err
					}
				}
			}
		}
		for _, path := range sortedImportPaths(fields, "/records/") {
			var wanted string
			if err := json.Unmarshal(fields[path], &wanted); err != nil {
				return Fail("INVALID_REQUEST", "Reviewed record identity needs a page")
			}
			var collection, page string
			err := q.QueryRowContext(ctx, "SELECT collection_id,page_id FROM records WHERE id=?", strings.TrimPrefix(path, "/records/")).Scan(&collection, &page)
			if err == nil && (collection != item.CollectionID || page != wanted) {
				return Fail("CONFLICT", "Reviewed record identity does not match its canonical collection and page")
			}
			if err != nil && !errors.Is(err, sql.ErrNoRows) {
				return err
			}
		}
	}
	if journalChanges > 128 {
		return Fail("RESOURCE_EXHAUSTED", "A reviewed import can migrate or delete at most 128 schema/record targets at once")
	}
	return validateReviewedImportDerivedGraph(ctx, q, p)
}

func validateReviewedImportDerivedGraph(ctx context.Context, q querier, p *ImportPlan) error {
	if !p.TypedDatabaseMerge || p.NotionCopyGraph {
		return nil
	}
	props := map[string]contracts.DomainPropertyDefinition{}
	rows, err := q.QueryContext(ctx, "SELECT id,collection_id,type,config_json FROM properties")
	if err != nil {
		return err
	}
	for rows.Next() {
		var prop contracts.DomainPropertyDefinition
		var config string
		if err = rows.Scan(&prop.Id, &prop.CollectionId, &prop.Type, &config); err != nil {
			rows.Close()
			return err
		}
		prop.Config = json.RawMessage(config)
		props[string(prop.Id)] = prop
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	for i := range p.Items {
		item := &p.Items[i]
		if item.Kind != "portable_collection" {
			continue
		}
		fields := selectedImportDatabaseFields(item)
		if item.Merge != nil {
			for _, field := range item.Merge.Fields {
				if strings.HasPrefix(field.Path, "/schema/") && field.Local.Present && fields[field.Path] == nil {
					delete(props, strings.TrimPrefix(field.Path, "/schema/"))
				}
			}
		}
		for _, path := range sortedImportPaths(fields, "/schema/") {
			var prop contracts.DomainPropertyDefinition
			if err = json.Unmarshal(fields[path], &prop); err != nil {
				return err
			}
			prop.Id, prop.CollectionId = contracts.DomainId(strings.TrimPrefix(path, "/schema/")), contracts.DomainId(item.CollectionID)
			props[string(prop.Id)] = prop
		}
	}
	collections := map[string]*PortableCollectionImport{}
	graph := map[string][]string{}
	for id, prop := range props {
		collection := string(prop.CollectionId)
		if collections[collection] == nil {
			collections[collection] = &PortableCollectionImport{CollectionID: collection}
		}
		collections[collection].Properties = append(collections[collection].Properties, prop)
		var config map[string]any
		_ = json.Unmarshal(prop.Config, &config)
		raw := asObject(config["raw"])
		if prop.Type == "formula" {
			if deps, err := formulaDependencies(str(raw["translatedExpression"])); err == nil {
				graph[id] = deps
			}
		}
		if prop.Type == "rollup" && str(raw["targetPropertyId"]) != "" {
			graph[id] = []string{str(raw["targetPropertyId"])}
		}
	}
	if graphCycle(graph) {
		return Fail("CONFLICT", "Reviewed formula/rollup choices form a dependency cycle")
	}
	plans := []PortableCollectionImport{}
	for _, collection := range collections {
		plans = append(plans, *collection)
	}
	if err = validatePortableDatabaseGraph(plans, nil); err != nil {
		return Fail("CONFLICT", "Reviewed property graph is inconsistent: "+err.Error())
	}
	return nil
}

func updateImportedProperty(m *Mutation, collection, id string, raw json.RawMessage) error {
	var definition struct {
		Name          string         `json:"name"`
		Type          string         `json:"type"`
		SchemaVersion int64          `json:"schemaVersion"`
		Config        map[string]any `json:"config"`
	}
	if err := json.Unmarshal(raw, &definition); err != nil || definition.SchemaVersion != 1 {
		return Fail("INVALID_REQUEST", "Invalid reviewed property definition")
	}
	if err := contracts.Validate("domain", "property_"+definition.Type+"_config_v1", marshal(definition.Config)); err != nil {
		return Fail("INVALID_REQUEST", "Invalid reviewed property configuration")
	}
	if err := guardImport(m, "property", id); err != nil {
		return err
	}
	current, err := propertyDefinition(m.Context, m.Tx, id)
	if errors.Is(err, sql.ErrNoRows) {
		return databaseCommand(m, map[string]any{"kind": "collection.addProperty", "collectionId": collection, "propertyId": id, "name": definition.Name, "type": definition.Type, "schemaVersion": float64(1), "config": definition.Config})
	}
	if err != nil {
		return err
	}
	if string(current.CollectionId) != collection {
		return Fail("SCOPE_DENIED", "Property moved outside the reviewed collection")
	}
	if current.Type != definition.Type {
		return Fail("CONFLICT", "Changing a property type requires a separate value conversion; keep its local schema or import a copy")
	}
	if string(importPropertyField(current)) == string(raw) {
		return nil
	}
	if err = m.Touch("collection", collection); err != nil {
		return err
	}
	if err = m.Touch("property", id); err != nil {
		return err
	}
	if current.Type == "select" || current.Type == "status" || current.Type == "multi_select" {
		wanted := map[string]bool{}
		groups := map[string]string{}
		for _, raw := range asList(definition.Config["options"]) {
			o := asObject(raw)
			oid := str(o["id"])
			if wanted[oid] {
				return Fail("INVALID_REQUEST", "Duplicate reviewed option identity")
			}
			wanted[oid] = true
			groups[oid] = str(o["group"])
			var owner string
			err = m.Tx.QueryRowContext(m.Context, "SELECT property_id FROM property_options WHERE id=?", oid).Scan(&owner)
			if err == nil && owner != id {
				return Fail("CONFLICT", "Option identity belongs to another property")
			}
			if err != nil && !errors.Is(err, sql.ErrNoRows) {
				return err
			}
			if _, err = m.Exec("INSERT INTO property_options VALUES(?,?,?,?) ON CONFLICT(id) DO UPDATE SET label=excluded.label,status_group=excluded.status_group", oid, id, o["label"], nullable(o["group"])); err != nil {
				return err
			}
		}
		rows, err := m.Tx.QueryContext(m.Context, "SELECT id FROM property_options WHERE property_id=?", id)
		if err != nil {
			return err
		}
		old := []string{}
		for rows.Next() {
			var oid string
			if err = rows.Scan(&oid); err != nil {
				rows.Close()
				return err
			}
			old = append(old, oid)
		}
		err = rows.Err()
		rows.Close()
		if err != nil {
			return err
		}
		for _, oid := range old {
			if !wanted[oid] {
				return Fail("CONFLICT", "Removing source options requires resolving existing values first; retain the option or import a copy")
			}
		}
		for _, name := range []string{"defaultOptionId", "doneOptionId", "reopenOptionId"} {
			if id := str(definition.Config[name]); id != "" {
				if !wanted[id] || name == "doneOptionId" && groups[id] != "done" || name == "reopenOptionId" && groups[id] == "done" {
					return Fail("INVALID_REQUEST", "Reviewed status mapping has an unknown or incompatible option")
				}
			}
		}
	}
	_, err = m.Exec("UPDATE properties SET name=?,config_json=? WHERE id=?", definition.Name, string(marshal(definition.Config)), id)
	return err
}

// A typed graph is a single final import unit. Guards captured by preview are
// advanced only by this import's own committed units; unrelated edits reject it.
func commitMergedImportDatabases(m *Mutation, p *ImportPlan) error {
	hidden, err := hiddenImportCollections(m.Context, m.Tx, p)
	if err != nil {
		return err
	}
	for i := range p.Items {
		if p.Items[i].Kind == "portable_collection" {
			if err := checkImportMergeGuards(m, &p.Items[i]); err != nil {
				return err
			}
		}
	}
	schemaActions := []map[string]any{}
	recordActions := []map[string]any{}
	deletedRecords := map[string]bool{}
	changedSchemas := map[string]bool{}
	for i := range p.Items {
		item := &p.Items[i]
		if item.Kind != "portable_collection" || item.Merge == nil || hidden[item.CollectionID] {
			continue
		}
		fields := selectedImportDatabaseFields(item)
		deletions, err := importRecordDeletions(m.Context, m.Tx, p, item)
		if err != nil {
			return err
		}
		for _, action := range deletions {
			deletedRecords[str(action["recordId"])] = true
		}
		recordActions = append(recordActions, deletions...)
		for _, field := range item.Merge.Fields {
			if !strings.HasPrefix(field.Path, "/schema/") || !field.Local.Present {
				continue
			}
			id := strings.TrimPrefix(field.Path, "/schema/")
			var before, after map[string]any
			_ = json.Unmarshal(field.Local.Value, &before)
			if raw := fields[field.Path]; raw != nil {
				_ = json.Unmarshal(raw, &after)
				if before["type"] == after["type"] {
					continue
				}
			}
			if fields[field.Path] == nil {
				if c := importCollectionFor(p, item); c == nil || !c.SchemaComplete {
					return Fail("CONFLICT", "Incomplete schema enumeration cannot establish a source property deletion")
				}
			}
			if err := validateImportSchemaChange(m.Context, m.Tx, item, id, fields[field.Path], fields); err != nil {
				return err
			}
			var owner string
			if err := m.Tx.QueryRowContext(m.Context, "SELECT owning_page_id FROM collections WHERE id=?", item.CollectionID).Scan(&owner); err != nil {
				return err
			}
			if err := importGuardPage(m, owner); err != nil {
				return err
			}
			action, err := importSchemaAction(item, id, fields[field.Path], fields)
			if err != nil {
				return err
			}
			schemaActions = append(schemaActions, action)
			changedSchemas[id] = true
		}
	}
	for i := range p.PortableCollections {
		c := &p.PortableCollections[i]
		var item *ImportItem
		for j := range p.Items {
			if p.Items[j].Kind == "portable_collection" && p.Items[j].CollectionID == c.CollectionID {
				item = &p.Items[j]
				break
			}
		}
		if item == nil {
			return Fail("INTEGRITY_ERROR", "Typed database has no reviewed item")
		}
		if hidden[c.CollectionID] {
			continue
		}
		fields := selectedImportDatabaseFields(item)
		for _, ref := range [][2]string{{"collection", c.CollectionID}, {"page", c.PageID}} {
			if err := guardImport(m, ref[0], ref[1]); err != nil {
				return err
			}
		}
		if m.GuardRevision("collection", c.CollectionID) == "0" {
			if err := guardImport(m, "property", string(c.Properties[0].Id)); err != nil {
				return err
			}
			if err := databaseCommand(m, map[string]any{"kind": "collection.create", "collectionId": c.CollectionID, "owningPageId": c.PageID, "titlePropertyId": string(c.Properties[0].Id), "title": c.Title}); err != nil {
				return err
			}
		}
		var title string
		if raw := fields["/collectionTitle"]; raw != nil {
			if err := json.Unmarshal(raw, &title); err != nil {
				return Fail("INVALID_REQUEST", "Collection title must be text")
			}
			if err := m.Touch("collection", c.CollectionID); err != nil {
				return err
			}
			if _, err := m.Exec("UPDATE collections SET title=? WHERE id=?", title, c.CollectionID); err != nil {
				return err
			}
		}
		for _, path := range sortedImportPaths(fields, "/schema/") {
			if changedSchemas[strings.TrimPrefix(path, "/schema/")] {
				continue
			}
			if err := updateImportedProperty(m, c.CollectionID, strings.TrimPrefix(path, "/schema/"), fields[path]); err != nil {
				return err
			}
		}
		// Missing records and properties are not tombstones; source deletion
		// requires a separate proven complete enumeration and explicit decision.
		for _, path := range sortedImportPaths(fields, "/records/") {
			rid := strings.TrimPrefix(path, "/records/")
			var page string
			if err := json.Unmarshal(fields[path], &page); err != nil {
				return Fail("INVALID_REQUEST", "Record identity needs a page")
			}
			if err := guardImport(m, "record", rid); err != nil {
				return err
			}
			if err := importGuardPage(m, page); err != nil {
				return err
			}
			if m.GuardRevision("record", rid) != "0" {
				var owner, existingPage string
				if err := m.Tx.QueryRowContext(m.Context, "SELECT collection_id,page_id FROM records WHERE id=?", rid).Scan(&owner, &existingPage); err != nil {
					return err
				}
				if owner != c.CollectionID || existingPage != page {
					return Fail("CONFLICT", "Reviewed record identity changed")
				}
				continue
			}
			if err := m.TouchPage(page); err != nil {
				return err
			}
			if err := requireNew(m, "record", rid); err != nil {
				return err
			}
			var order int64
			var rev string
			if err := m.Tx.QueryRowContext(m.Context, "SELECT COALESCE(MAX(CAST(sort_key AS INTEGER)),0)+1 FROM records WHERE collection_id=?", c.CollectionID).Scan(&order); err != nil {
				return err
			}
			if err := m.Tx.QueryRowContext(m.Context, "SELECT revision FROM pages WHERE id=?", page).Scan(&rev); err != nil {
				return err
			}
			if _, err := m.Exec("INSERT INTO records VALUES(?,?,?,?,?)", rid, c.CollectionID, page, fmt.Sprintf("%012d", order), rev); err != nil {
				return err
			}
			change := m.touched[guardKey("record", rid)]
			change.After = m.touched[guardKey("page", page)].After
			m.touched[guardKey("record", rid)] = change
		}
	}
	// New rows now exist. Add guards for the complete old/new value inventory
	// and apply each schema with its typed values as one recoverable operation.
	for _, action := range schemaActions {
		before, err := schemaJournalCurrent(m.Context, m.Tx, action)
		if err != nil {
			return err
		}
		for _, record := range schemaValueRecords(before.Before, action) {
			var page string
			if err := m.Tx.QueryRowContext(m.Context, "SELECT page_id FROM records WHERE id=? AND collection_id=?", record, action["collectionId"]).Scan(&page); err != nil {
				return err
			}
			if err := importGuardPage(m, page); err != nil {
				return err
			}
		}
		if err := guardImport(m, "property", str(action["propertyId"])); err != nil {
			return err
		}
	}
	for _, action := range recordActions {
		var page, collection string
		if err := m.Tx.QueryRowContext(m.Context, "SELECT page_id,collection_id FROM records WHERE id=?", action["recordId"]).Scan(&page, &collection); err != nil {
			return err
		}
		if err := importGuardPage(m, page); err != nil {
			return err
		}
		if err := guardImport(m, "collection", collection); err != nil {
			return err
		}
	}
	schemaActions = append(schemaActions, recordActions...)
	if len(schemaActions) > 0 {
		if err := applyJournal(m, p.ID, "Reviewed import schema, value and deletion changes", schemaActions); err != nil {
			return err
		}
	}
	// Every record exists before relation values are validated and applied.
	for i := range p.Items {
		item := &p.Items[i]
		if item.Kind != "portable_collection" {
			continue
		}
		if hidden[item.CollectionID] {
			if err := saveImportBaseline(m, p, item); err != nil {
				return err
			}
			continue
		}
		fields := selectedImportDatabaseFields(item)
		for _, path := range sortedImportPaths(fields, "/values/") {
			parts := strings.Split(path, "/")
			if len(parts) != 4 {
				return Fail("INVALID_REQUEST", "Invalid reviewed record value path")
			}
			rid, pid := parts[2], parts[3]
			if changedSchemas[pid] || deletedRecords[rid] {
				continue
			}
			if err := guardImport(m, "record", rid); err != nil {
				return err
			}
			if err := guardImport(m, "property", pid); err != nil {
				return err
			}
			var page string
			if err := m.Tx.QueryRowContext(m.Context, "SELECT page_id FROM records WHERE id=? AND collection_id=?", rid, item.CollectionID).Scan(&page); err != nil {
				return err
			}
			if err := importGuardPage(m, page); err != nil {
				return err
			}
			var current string
			err := m.Tx.QueryRowContext(m.Context, "SELECT value_json FROM property_values WHERE record_id=? AND property_id=?", rid, pid).Scan(&current)
			if err == nil && current == string(fields[path]) {
				continue
			}
			if err != nil && !errors.Is(err, sql.ErrNoRows) {
				return err
			}
			prop, err := propertyDefinition(m.Context, m.Tx, pid)
			if err != nil {
				return err
			}
			var value any
			if err = json.Unmarshal(fields[path], &value); err != nil {
				return err
			}
			if prop.Type == "formula" || prop.Type == "rollup" {
				if err = m.TouchPage(page); err != nil {
					return err
				}
				if err = validatePropertyValue(m, prop, value); err != nil {
					return err
				}
				if _, err = m.Exec("INSERT INTO property_values VALUES(?,?,?,?,?,?) ON CONFLICT(record_id,property_id) DO UPDATE SET value_json=excluded.value_json", rid, item.CollectionID, pid, prop.Type, prop.SchemaVersion, string(fields[path])); err != nil {
					return err
				}
			} else if err = setRecordValue(m, rid, pid, map[string]any{"type": prop.Type, "schemaVersion": float64(prop.SchemaVersion), "value": value}); err != nil {
				return err
			}
		}
		if item.Merge != nil {
			for _, field := range item.Merge.Fields {
				if !strings.HasPrefix(field.Path, "/values/") || !field.Local.Present {
					continue
				}
				if _, exists := fields[field.Path]; exists {
					continue
				}
				parts := strings.Split(field.Path, "/")
				rid, pid := parts[2], parts[3]
				if changedSchemas[pid] || deletedRecords[rid] {
					continue
				}
				if err := guardImport(m, "record", rid); err != nil {
					return err
				}
				if err := guardImport(m, "property", pid); err != nil {
					return err
				}
				var page string
				if err := m.Tx.QueryRowContext(m.Context, "SELECT page_id FROM records WHERE id=?", rid).Scan(&page); err != nil {
					return err
				}
				if err := importGuardPage(m, page); err != nil {
					return err
				}
				if err := clearRecordValue(m, rid, pid); err != nil {
					return err
				}
			}
		}
		if err := saveImportBaseline(m, p, item); err != nil {
			return err
		}
	}
	if err := commitNotionContainers(m, p); err != nil {
		return err
	}
	for _, c := range p.PortableCollections {
		preserveViews := false
		for _, item := range p.Items {
			if item.Kind == "portable_collection" && item.CollectionID == c.CollectionID && item.Merge != nil {
				preserveViews = true
			}
		}
		if preserveViews {
			continue
		}
		for _, v := range c.Views {
			if err := guardImport(m, "view", v.ID); err != nil {
				return err
			}
			if m.GuardRevision("view", v.ID) != "0" {
				continue
			} // Existing view presentation is local until separately reviewed.
			if err := importGuardPage(m, v.OwningPageID); err != nil {
				return err
			}
			if err := saveView(m, map[string]any{"kind": "view.save", "viewId": v.ID, "containerId": v.ContainerID, "collectionId": c.CollectionID, "owningPageId": v.OwningPageID, "name": v.Name, "type": v.Type, "schemaVersion": float64(v.SchemaVersion), "config": v.Config, "query": v.Query}); err != nil {
				return err
			}
		}
	}
	if err := persistCSVKeyBindings(m, p); err != nil {
		return err
	}
	return persistImportDatabaseIdentities(m, p)
}
func sortedImportPaths(fields map[string]json.RawMessage, prefix string) []string {
	out := []string{}
	for path := range fields {
		if strings.HasPrefix(path, prefix) {
			out = append(out, path)
		}
	}
	sort.Strings(out)
	return out
}

func importSchemaAction(item *ImportItem, id string, raw json.RawMessage, fields map[string]json.RawMessage) (map[string]any, error) {
	var definition any
	if raw != nil {
		if err := json.Unmarshal(raw, &definition); err != nil {
			return nil, err
		}
	}
	values := []any{}
	for _, path := range sortedImportPaths(fields, "/values/") {
		parts := strings.Split(path, "/")
		if len(parts) != 4 || parts[3] != id {
			continue
		}
		var value any
		if err := json.Unmarshal(fields[path], &value); err != nil {
			return nil, err
		}
		values = append(values, map[string]any{"recordId": parts[2], "value": value})
	}
	return map[string]any{"kind": "collection.property.restore", "collectionId": item.CollectionID, "propertyId": id, "definition": definition, "valueInventoryVersion": 1, "values": values}, nil
}
func validateImportSchemaChange(ctx context.Context, q querier, item *ImportItem, id string, raw json.RawMessage, fields map[string]json.RawMessage) error {
	action, err := importSchemaAction(item, id, raw, fields)
	if err != nil {
		return err
	}
	return validateReviewedPropertyRestore(ctx, q, action)
}
